-- B1 캘린더용 온통청년 청년정책(2계층)과 신청 회차, Y-Fin 정책상품(1계층)의 신청 회차.
-- 수집기(Fin-API)가 온통청년 API에서 채우고, Fin-BE는 캘린더 조회에만 쓴다.
-- 추천 대상인 product와 섞이지 않도록 별도 테이블로 둔다.
-- V9는 PR #41(저축기간 옵션)이 쓴다. 이 마이그레이션은 #41 머지 후에 머지해야 dev DB에서 순서가 맞는다.
--
-- apply_period_type: 온통청년 신청기간 구분(aplyPrdSeCd). PERIOD(특정기간) / ALWAYS(상시) / CLOSED(마감)
-- region_codes: 온통청년 zipCd 원문(시군구 5자리 코드, 쉼표 구분). 비어 있으면 지역 제한 없음.
-- min_age / max_age: NULL이면 그쪽 제한 없음(온통청년은 제한 없음을 0으로 준다).
-- synced_at: 수집에서 마지막으로 본 시각. 캘린더의 데이터 기준일로 쓴다.
-- is_active: 온통청년 목록에서 사라진 정책은 false.
CREATE TABLE IF NOT EXISTS youth_policy
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_no         VARCHAR(50)              NOT NULL,
    name              TEXT                     NOT NULL,
    institution       TEXT,
    summary           TEXT,
    min_age           INTEGER,
    max_age           INTEGER,
    region_codes      TEXT,
    apply_period_type VARCHAR(20)              NOT NULL,
    is_active         BOOLEAN                  NOT NULL DEFAULT TRUE,
    synced_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_youth_policy_policy_no UNIQUE (policy_no)
);

-- 신청 회차. 온통청년 aplyYmd의 "시작 ~ 종료" 하나가 한 행이다. round_no는 aplyYmd 안의 순서(1부터).
-- schedule_changed_at: 수집 때 날짜가 바뀐 시각. 캘린더는 7일간 '일정 변경'으로 표시한다.
CREATE TABLE IF NOT EXISTS youth_policy_round
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_id           BIGINT                   NOT NULL REFERENCES youth_policy (id) ON DELETE CASCADE,
    round_no            INTEGER                  NOT NULL,
    apply_start_date    DATE                     NOT NULL,
    apply_end_date      DATE                     NOT NULL,
    schedule_changed_at TIMESTAMP WITH TIME ZONE,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_youth_policy_round_policy_round_no UNIQUE (policy_id, round_no)
);

CREATE INDEX IF NOT EXISTS idx_youth_policy_round_dates
    ON youth_policy_round (apply_start_date, apply_end_date);

-- 1계층(Y-Fin 정책상품, product)의 신청 회차. 온통청년과 연결 키가 없어 운영자가 확인한 회차만 둔다(PRD).
-- 수집기가 manual-product-rounds.json에서 채운다. round_no는 파일 안 상품별 회차 순서(1부터).
-- source_url: 신청기간 근거(공고문, 보도자료 등).
CREATE TABLE IF NOT EXISTS policy_product_round
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id          BIGINT                   NOT NULL REFERENCES product (id) ON DELETE CASCADE,
    round_no            INTEGER                  NOT NULL,
    apply_start_date    DATE                     NOT NULL,
    apply_end_date      DATE                     NOT NULL,
    source_url          TEXT,
    schedule_changed_at TIMESTAMP WITH TIME ZONE,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_policy_product_round_product_round_no UNIQUE (product_id, round_no)
);

CREATE INDEX IF NOT EXISTS idx_policy_product_round_dates
    ON policy_product_round (apply_start_date, apply_end_date);
